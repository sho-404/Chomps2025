"""Generate chomps/_prompt_templates.py from the competition scripts.

The judge and retrieval prompts of the submission live as f-strings inside the
original scripts (english/spanish/scripts/...). Transcribing them by hand loses
trailing spaces and indented blank lines, which changes the request bytes and
therefore the cache keys and, potentially, model behaviour. This script reads
the f-strings with `ast`, renders them with sentinel values, and writes the
result as plain string templates with `{ctx}`, `{user_prompt}`,
`{model_answer}`, `{question}`, `{paper_text}` placeholders that prompts.py
fills with str.replace. Re-run it whenever the original scripts change:

    ../.venv/bin/python -m chomps.extract_prompts

tests/test_prompts.py checks that prompts.py reproduces the originals byte for byte.
"""
import ast
from pathlib import Path

from . import config

SENT = {"context": "\x00CTX\x00", "user_prompt": "\x00UP\x00", "model_answer": "\x00MA\x00",
        "question": "\x00Q\x00", "paper_text": "\x00PT\x00"}
PLACEHOLDER = {"\x00CTX\x00": "{ctx}", "\x00UP\x00": "{user_prompt}", "\x00MA\x00": "{model_answer}",
               "\x00Q\x00": "{question}", "\x00PT\x00": "{paper_text}"}


def _func(path: Path, name: str) -> ast.FunctionDef:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    for node in ast.walk(tree):
        if isinstance(node, ast.FunctionDef) and node.name == name:
            return node
    raise KeyError(f"{name} not in {path}")


def _render(node: ast.expr) -> str:
    expr = ast.Expression(body=node)
    ast.fix_missing_locations(expr)
    # Slices such as context[:60000] are applied to the sentinel, which is
    # shorter than any cap, so the sentinel survives intact.
    return eval(compile(expr, "<prompt>", "eval"), {"__builtins__": {}}, dict(SENT))


def _template(fn: ast.FunctionDef, var: str = None) -> str:
    if var is None:  # the function returns the f-string directly
        node = [n for n in ast.walk(fn) if isinstance(n, ast.Return)][0].value
    else:
        node = [n.value for n in ast.walk(fn) if isinstance(n, ast.Assign)
                and len(n.targets) == 1 and isinstance(n.targets[0], ast.Name) and n.targets[0].id == var][0]
    text = _render(node)
    for s, p in PLACEHOLDER.items():
        text = text.replace(s, p)
    if "\x00" in text:
        raise ValueError("unreplaced sentinel in template")
    return text


def _system(fn: ast.FunctionDef) -> str:
    for n in ast.walk(fn):
        if isinstance(n, ast.Dict):
            kv = {k.value: v for k, v in zip(n.keys, n.values) if isinstance(k, ast.Constant)}
            if isinstance(kv.get("role"), ast.Constant) and kv["role"].value == "system":
                return kv["content"].value
    raise KeyError("no system message in function")


def extract() -> dict:
    s = config.CODE_ROOT
    en_fact = _func(s / "english/scripts/factuality/approach_1_single_agent.py", "evaluate_factuality")
    es_fact = _func(s / "spanish/scripts/factuality/approach_1_single_agent.py", "evaluate_factuality")
    en_flu = _func(s / "english/scripts/fluency/approach_1_single_agent.py", "evaluate_fluency")
    es_flu = _func(s / "spanish/scripts/fluency/approach_1_single_agent.py", "evaluate_fluency_es")
    retr = _func(s / "english/scripts/inject_context_single_block.py", "get_context_from_llm")
    return {
        "FACTUALITY_USER": {"english": _template(en_fact, "eval_prompt"), "spanish": _template(es_fact, "eval_prompt")},
        "FLUENCY_USER": {"english": _template(en_flu, "eval_prompt"), "spanish": _template(es_flu, "eval_prompt")},
        "JUDGE_SYSTEM": {"english": _system(en_fact), "spanish": _system(es_fact)},
        "FLUENCY_SYSTEM": {"english": _system(en_flu), "spanish": _system(es_flu)},
        "RETRIEVAL_USER": _template(retr, "prompt"),
        "RETRIEVAL_SYSTEM": _system(retr),
    }


def main():
    t = extract()
    out = Path(__file__).with_name("_prompt_templates.py")
    lines = ['"""GENERATED by chomps/extract_prompts.py from the competition scripts. Do not edit."""', ""]
    for k, v in t.items():
        lines.append(f"{k} = {v!r}")
        lines.append("")
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out} with {len(t)} templates")


if __name__ == "__main__":
    main()
